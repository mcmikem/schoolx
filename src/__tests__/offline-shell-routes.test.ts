import { execFileSync } from "node:child_process";
import * as fs from "node:fs";
import * as path from "node:path";

const ROOT = path.join(__dirname, "..", "..");
const read = (relativePath: string): string => fs.readFileSync(path.join(ROOT, relativePath), "utf8");

// The manifest is generated during prebuild and is intentionally not tracked.
execFileSync(process.execPath, ["scripts/generate-offline-routes.mjs"], { cwd: ROOT, stdio: "ignore" });

describe("offline route manifest", () => {
  const manifest = JSON.parse(read("public/offline-routes.json")) as {
    version: string;
    routes: string[];
  };

  it("includes the app routes a signed-in user needs offline", () => {
    expect(manifest.routes).toContain("/dashboard/");
    expect(manifest.routes).toContain("/dashboard/attendance/");
    expect(manifest.routes).toContain("/dashboard/students/");
    expect(manifest.routes).toContain("/parent-portal/");
    expect(manifest.routes).toContain("/student-portal/");
    expect(manifest.routes).toContain("/super-admin/");
  });

  it("never tries to download a parameterised or dev-only route", () => {
    expect(manifest.routes.some((route) => route.includes("["))).toBe(false);
    expect(manifest.routes).not.toContain("/demo/");
    expect(manifest.routes).not.toContain("/demo-login/");
    expect(manifest.routes).not.toContain("/demo-student/");
  });

  it("is regenerated by the build before Next copies public/", () => {
    const pkg = JSON.parse(read("package.json")) as { scripts: Record<string, string> };
    expect(pkg.scripts.prebuild).toContain("generate-offline-routes.mjs");
  });
});

describe("offline shell labels substitutions", () => {
  const sw = read("public/sw.js");

  it("marks a nearest-page fallback with the path the user asked for", () => {
    expect(sw).toContain("markOfflineFallback");
    expect(sw).toContain("__SKOOLMATE_OFFLINE_FALLBACK__");
    expect(sw).toContain("markOfflineFallback(nearest, url.pathname)");
  });

  it("accepts background route warm-ups from the signed-in app", () => {
    expect(sw).toContain("WARM_ROUTE");
    expect(sw).toContain("warmRoute");
  });

  it("precaches the parent, student and super-admin shells too", () => {
    expect(sw).toContain("'/parent-portal/'");
    expect(sw).toContain("'/student-portal/'");
    expect(sw).toContain("'/super-admin/'");
  });
});

describe("offline background warmers", () => {
  const providers = read("src/app/providers.tsx");

  it("mounts both the page and table warmers for signed-in users", () => {
    expect(providers).toContain("OfflineRouteWarmer");
    expect(providers).toContain("OfflineDataWarmer");
  });

  it("pages table downloads instead of asking for everything at once", () => {
    expect(read("src/lib/offline.ts")).toContain("warmTables");
    expect(read("src/lib/offline-data-warmer.tsx")).toContain("warmTables");
  });

  it("prepares essential teacher and bursar data while Data Saver is enabled", () => {
    const warmer = read("src/lib/offline-data-warmer.tsx");
    expect(warmer).toContain("ESSENTIAL_OFFLINE_DATA_TABLES");
    expect(warmer).toContain('"attendance"');
    expect(warmer).toContain('"grades"');
    expect(warmer).toContain('"fee_payments"');
    expect(warmer).toContain("{ pageSize: 100, maxRows: 100 }");
  });

  it("limits offline page downloads to core work screens on weak connections", () => {
    const warmer = read("src/lib/offline-route-warmer.tsx");
    expect(warmer).toContain('"/dashboard/money/"');
    expect(warmer).toContain('"/dashboard/fee-structure/"');
    expect(warmer).toContain('"/dashboard/messages/"');
    expect(warmer).toContain("PRIORITY_ROUTES.filter((route) => roleRoutes.includes(route))");
  });
});

describe("offline warm-up survives cache eviction and new deploys", () => {
  const sw = read("public/sw.js");
  const warmer = read("src/lib/offline-route-warmer.tsx");

  it("asks the worker which routes are actually in the page cache", () => {
    expect(sw).toContain("CHECK_ROUTES_RESULT");
    expect(sw).toContain("pageCache.match(route)");
    expect(warmer).toContain("checkRoutesWithWorker");
    expect(warmer).toContain("new Set(cacheState.cached)");
  });

  it("scopes the done list to the deployed cache generation", () => {
    expect(warmer).toContain("`${manifest.version}:${cacheState.version}`");
    const generator = read("scripts/generate-offline-routes.mjs");
    expect(generator).toContain("VERCEL_GIT_COMMIT_SHA");
  });

  it("starts filling the cache sooner after sign-in", () => {
    const startDelay = Number(warmer.match(/START_DELAY_MS = (\d+)/)?.[1]);
    expect(startDelay).toBeLessThanOrEqual(5_000);
  });
});
