"use client";

import { Document, Page, Text, View, StyleSheet, pdf } from "@react-pdf/renderer";

const styles = StyleSheet.create({
  page: { padding: 40, fontSize: 11, fontFamily: "Helvetica" },
  header: { textAlign: "center", marginBottom: 16 },
  school: { fontSize: 16, fontWeight: "bold", marginBottom: 2 },
  title: { fontSize: 12, color: "#555", marginBottom: 12 },
  section: { marginBottom: 12 },
  row: { flexDirection: "row", marginBottom: 4 },
  label: { width: 120, fontWeight: "bold", color: "#333" },
  value: { flex: 1 },
  table: { marginTop: 8, borderTop: "1px solid #ccc" },
  tableHeader: { flexDirection: "row", backgroundColor: "#f0f0f0", padding: 4, fontWeight: "bold" },
  tableRow: { flexDirection: "row", padding: 4, borderBottom: "1px solid #eee" },
  col1: { flex: 2 },
  col2: { flex: 1, textAlign: "center" },
  col3: { flex: 1, textAlign: "center" },
  footer: { marginTop: 20, fontSize: 9, color: "#888", textAlign: "center" },
});

export interface ReportPDFData {
  schoolName: string;
  studentName: string;
  studentNumber: string;
  className: string;
  term: number;
  academicYear: string;
  subjects: { name: string; score: number; grade: string }[];
  classTeacherRemark?: string;
  headTeacherRemark?: string;
  feeBalance?: number | null;
}

export function StudentReportDocument({ data }: { data: ReportPDFData }) {
  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <View style={styles.header}>
          <Text style={styles.school}>{data.schoolName}</Text>
          <Text style={styles.title}>
            Student Report Card — Term {data.term}, {data.academicYear}
          </Text>
        </View>

        <View style={styles.section}>
          <View style={styles.row}>
            <Text style={styles.label}>Student:</Text>
            <Text style={styles.value}>{data.studentName}</Text>
          </View>
          <View style={styles.row}>
            <Text style={styles.label}>Student No:</Text>
            <Text style={styles.value}>{data.studentNumber}</Text>
          </View>
          <View style={styles.row}>
            <Text style={styles.label}>Class:</Text>
            <Text style={styles.value}>{data.className}</Text>
          </View>
        </View>

        <View style={styles.table}>
          <View style={styles.tableHeader}>
            <Text style={styles.col1}>Subject</Text>
            <Text style={styles.col2}>Score</Text>
            <Text style={styles.col3}>Grade</Text>
          </View>
          {data.subjects.map((s, i) => (
            <View key={i} style={styles.tableRow}>
              <Text style={styles.col1}>{s.name}</Text>
              <Text style={styles.col2}>{s.score}</Text>
              <Text style={styles.col3}>{s.grade}</Text>
            </View>
          ))}
        </View>

        {data.classTeacherRemark && (
          <View style={styles.section}>
            <Text style={styles.label}>Class Teacher:</Text>
            <Text>{data.classTeacherRemark}</Text>
          </View>
        )}
        {data.headTeacherRemark && (
          <View style={styles.section}>
            <Text style={styles.label}>Head Teacher:</Text>
            <Text>{data.headTeacherRemark}</Text>
          </View>
        )}
        {data.feeBalance != null && (
          <View style={styles.section}>
            <Text style={styles.label}>Fee Balance:</Text>
            <Text>{data.feeBalance > 0 ? `UGX ${data.feeBalance.toLocaleString()}` : "Cleared"}</Text>
          </View>
        )}

        <Text style={styles.footer}>Generated by SkoolMate OS</Text>
      </Page>
    </Document>
  );
}

export async function downloadReportPDF(data: ReportPDFData, filename: string) {
  const blob = await pdf(<StudentReportDocument data={data} />).toBlob();
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
